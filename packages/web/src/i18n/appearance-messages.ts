/**
 * Built-in themes are product copy and follow the selected UI locale. Custom
 * and extension-package themes are user/package content: preserve their
 * metadata verbatim and let the caller mark that content in the UI.
 */
export function getLocalizedThemeText(theme: ThemeTextSource, locale: UiLocale): LocalizedThemeText {
  if (theme.source !== 'builtin' || !BUILTIN_THEME_IDS.includes(theme.id as BuiltinThemeId)) {
    return { displayName: theme.displayName, description: theme.description }
  }
  return BUILTIN_THEME_TEXT[locale][theme.id as BuiltinThemeId]
}
